-- Função para juntar duas tabelas de ASCII
local function merge_ascii(a, b)
  local result = {}
  for _, line in ipairs(a) do
    table.insert(result, line)
  end
  for _, line in ipairs(b) do
    table.insert(result, line)
  end
  return result
end

